<?php
$select_query_daily = "
SELECT
  ARCAT.ARCAT_CODE,
  ARCAT.ARCAT_NAME,
  ARFILE.AR_CODE,
  ARFILE.AR_NAME,
  FORMAT(DOCINFO.DI_DATE, 'dd/MM/yyyy') AS DI_DATE,
  DOCINFO.DI_REF,
  DOCINFO.DI_REMARK,
  DOCTYPE.DT_PROPERTIES,
  DOCTYPE.DT_DOCCODE,
  SKUMASTER.SKU_CODE,
  SKUMASTER.SKU_NAME,
  GOODSMASTER.GOODS_CODE,
  BRAND.BRN_CODE,
  BRAND.BRN_NAME,
  TRANSTKD.TRD_SEQ,
  TRANSTKH.TRH_VATIO,
  TRANSTKD.TRD_SH_CODE,
  TRANSTKD.TRD_SH_NAME,
  TRANSTKD.TRD_LOT_NO,
  TRANSTKD.TRD_SERIAL,
  TRANSTKD.TRD_UTQNAME,
  TRANSTKD.TRD_U_PRC,
  TRANSTKD.TRD_Q_FREE,
  TRANSTKD.TRD_QTY,
  TRANSTKD.TRD_DSC_KEYIN,
  TRANSTKD.TRD_DSC_KEYINV,
  TRANSTKD.TRD_TDSC_KEYINV,
  TRANSTKD.TRD_G_KEYIN,
  TRANSTKD.TRD_G_SELL,
  TRANSTKD.TRD_G_VAT,
  TRANSTKD.TRD_B_AMT,
  TRANSTKD.TRD_B_SELL,
  TRANSTKD.TRD_B_VAT,
  TRANSTKD.TRD_VAT_TY,
  EXCHANGERATE.CRNCY_CODE,
  EXCHANGERATE.CRNCY_NAME,
  ARDETAIL.ARD_XCHG,
  ARDETAIL.ARD_TDSC_KEYIN,
  ARDETAIL.ARD_TDSC_KEYINV,
  SALESMAN.SLMN_SLT,
  SALESMAN.SLMN_CODE,
  SALESMAN.SLMN_NAME,
  WARELOCATION.WL_CODE,
  ICCAT.ICCAT_CODE,
  ICCAT.ICCAT_NAME,
  DOCINFO.DI_KEY,
  DAY(DI_DATE) AS DI_DAY,
  MONTH(DI_DATE) AS DI_MONTH,
  YEAR(DI_DATE) AS DI_YEAR,
  FORMAT(CAST(DOCINFO.DI_CRE_DATE AS datetime), 'HH:mm') AS DI_TIME_CHK,
  DOCINFO.DI_ACTIVE,
  SHIPBY.SB_NAME,
  TRANSTKH.TRH_SHIP_REMARK,
  Single_ARPLU.ARPLU_U_PRC,
  Single_ARPLU.ARPLU_U_DSC
FROM
  DOCINFO WITH (NOLOCK)
  INNER JOIN DOCTYPE WITH (NOLOCK)
    ON DOCINFO.DI_DT = DOCTYPE.DT_KEY
  INNER JOIN TRANSTKH WITH (NOLOCK)
    ON DOCINFO.DI_KEY = TRANSTKH.TRH_DI
  INNER JOIN TRANSTKD WITH (NOLOCK)
    ON TRANSTKH.TRH_KEY = TRANSTKD.TRD_TRH
  INNER JOIN ARDETAIL WITH (NOLOCK)
    ON DOCINFO.DI_KEY = ARDETAIL.ARD_DI
  INNER JOIN VATTABLE WITH (NOLOCK)
    ON DOCINFO.DI_KEY = VATTABLE.VAT_DI
  INNER JOIN EXCHANGERATE WITH (NOLOCK)
    ON ARDETAIL.ARD_CRNCYCODE = EXCHANGERATE.CRNCY_CODE
  INNER JOIN ARFILE WITH (NOLOCK)
    ON ARDETAIL.ARD_AR = ARFILE.AR_KEY
  INNER JOIN GOODSMASTER WITH (NOLOCK)
    ON TRANSTKD.TRD_GOODS = GOODSMASTER.GOODS_KEY
  INNER JOIN SKUMASTER WITH (NOLOCK)
    ON TRANSTKD.TRD_SKU = SKUMASTER.SKU_KEY
  INNER JOIN SHIPBY WITH (NOLOCK)
    ON TRANSTKH.TRH_SB = SHIPBY.SB_KEY
  INNER JOIN ARCAT WITH (NOLOCK)
    ON ARFILE.AR_ARCAT = ARCAT.ARCAT_KEY
  INNER JOIN ICCAT WITH (NOLOCK)
    ON SKUMASTER.SKU_ICCAT = ICCAT.ICCAT_KEY
  INNER JOIN ICDEPT WITH (NOLOCK)
    ON SKUMASTER.SKU_ICDEPT = ICDEPT.ICDEPT_KEY
  INNER JOIN BRAND WITH (NOLOCK)
    ON SKUMASTER.SKU_BRN = BRAND.BRN_KEY
  INNER JOIN SKUALT WITH (NOLOCK)
    ON SKUMASTER.SKU_SKUALT = SKUALT.SKUALT_KEY
  INNER JOIN ICCOLOR WITH (NOLOCK)
    ON SKUMASTER.SKU_ICCOLOR = ICCOLOR.ICCOLOR_KEY
  INNER JOIN ICSIZE WITH (NOLOCK)
    ON SKUMASTER.SKU_ICSIZE = ICSIZE.ICSIZE_KEY
  INNER JOIN PRJTAB WITH (NOLOCK)
    ON TRANSTKH.TRH_PRJ = PRJTAB.PRJ_KEY
  INNER JOIN DEPTTAB WITH (NOLOCK)
    ON TRANSTKH.TRH_DEPT = DEPTTAB.DEPT_KEY
  INNER JOIN BRANCH WITH (NOLOCK)
    ON TRANSTKH.TRH_BR = BRANCH.BR_KEY
  INNER JOIN MKTPLAN WITH (NOLOCK)
    ON TRANSTKH.TRH_MKTP = MKTPLAN.MKTP_KEY
  INNER JOIN PRMTPLAN WITH (NOLOCK)
    ON TRANSTKH.TRH_PRMT = PRMTPLAN.PRMT_KEY
  INNER JOIN WARELOCATION WITH (NOLOCK)
    ON TRANSTKD.TRD_WL = WARELOCATION.WL_KEY
  INNER JOIN WAREHOUSE WITH (NOLOCK)
    ON WARELOCATION.WL_WH = WAREHOUSE.WH_KEY
  INNER JOIN SLDETAIL WITH (NOLOCK)
    ON SLDETAIL.SLD_DI = DOCINFO.DI_KEY
  INNER JOIN SALESMAN WITH (NOLOCK)
    ON SLDETAIL.SLD_SLMN = SALESMAN.SLMN_KEY
  -- ***ส่วนที่แก้ไข: เพิ่ม WITH (NOLOCK) ใน Subquery ด้วย***
  LEFT JOIN (
      SELECT
          T1.*
      FROM
          ARPLU T1 WITH (NOLOCK)
          INNER JOIN ARPRICETAB T2 WITH (NOLOCK) ON T1.ARPLU_ARPRB = T2.ARPRB_KEY
      WHERE
          T2.ARPRB_CODE = 'S1'
          AND T1.ARPLU_KEY = (
              SELECT TOP 1 T3.ARPLU_KEY
              FROM ARPLU T3 WITH (NOLOCK)
                  INNER JOIN ARPRICETAB T4 WITH (NOLOCK) ON T3.ARPLU_ARPRB = T4.ARPRB_KEY
              WHERE
                  T3.ARPLU_GOODS = T1.ARPLU_GOODS AND T4.ARPRB_CODE = 'S1'
              ORDER BY T3.ARPLU_KEY ASC
          )
  ) AS Single_ARPLU
    ON Single_ARPLU.ARPLU_GOODS = GOODSMASTER.GOODS_KEY
";

$select_query_daily_cond = "
WHERE
  ( DOCTYPE.DT_PROPERTIES = 302 OR
    DOCTYPE.DT_PROPERTIES = 307 OR
    DOCTYPE.DT_PROPERTIES = 308 OR
    DOCTYPE.DT_PROPERTIES = 337 ) 
    AND DOCINFO.DI_ACTIVE = 0 ";

//$select_query_daily_cond .= " AND (DOCTYPE.DT_DOCCODE = '2' OR DOCTYPE.DT_DOCCODE = 'DS02' -- เพิ่ม 'DS02' กลับเข้ามาตามเงื่อนไขเดิม ) ";
$select_query_daily_cond .= " AND (DOCTYPE.DT_DOCCODE = '2') ";

$select_query_daily_order = "
ORDER BY
DOCINFO.DI_DATE ASC,
DOCINFO.DI_REF ASC ,
ARCAT.ARCAT_CODE ASC,
ARFILE.AR_CODE ASC,
TRANSTKD.TRD_SEQ ASC ";