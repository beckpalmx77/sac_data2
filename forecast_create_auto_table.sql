-- SQL Command to create ims_forecast_auto table
-- This table is used for the Auto Forecast feature (forecast_auto.php)

CREATE TABLE IF NOT EXISTS `ims_forecast_auto` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `target_month` INT NOT NULL COMMENT 'เดือนเป้าหมาย (1-12)',
    `target_year` INT NOT NULL COMMENT 'ปีเป้าหมาย (ค.ศ.)',
    `group_by` VARCHAR(50) NOT NULL DEFAULT 'SKU_ONLY' COMMENT 'มุมมองจัดกลุ่ม (SKU_ONLY, AR_ONLY, AR_SKU)',
    `algorithm` VARCHAR(50) DEFAULT 'AUTO_BEST_FIT' COMMENT 'สูตรการคำนวณที่ใช้',
    `growth_factor` DECIMAL(5,2) DEFAULT 0.00 COMMENT '% ปรับแต่งการเติบโต',
    `ar_code` VARCHAR(50) NOT NULL DEFAULT '-' COMMENT 'รหัสลูกค้า',
    `ar_name` VARCHAR(255) DEFAULT NULL COMMENT 'ชื่อลูกค้า',
    `sku_code` VARCHAR(100) NOT NULL DEFAULT '-' COMMENT 'รหัสสินค้า',
    `sku_name` VARCHAR(255) DEFAULT NULL COMMENT 'ชื่อสินค้า',
    `brand` VARCHAR(100) DEFAULT NULL COMMENT 'ยี่ห้อสินค้า',
    `sku_cat` VARCHAR(100) DEFAULT NULL COMMENT 'ประเภทสินค้า',
    `sale_name` VARCHAR(255) DEFAULT NULL COMMENT 'พนักงานขาย',
    `take_name` VARCHAR(255) DEFAULT NULL COMMENT 'ผู้เทค',
    `amphur` VARCHAR(100) DEFAULT NULL COMMENT 'อำเภอ',
    `province` VARCHAR(100) DEFAULT NULL COMMENT 'จังหวัด',
    `unit_price` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ราคาขายเฉลี่ย',
    `qty_m3` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ยอดขายเดือน M-3',
    `qty_m2` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ยอดขายเดือน M-2',
    `qty_m1` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ยอดขายเดือน M-1',
    `avg_3m` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ยอดขายเฉลี่ย 3 เดือน',
    `qty_yoy` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ยอดขายเดือนเดียวกันปีที่แล้ว',
    `forecast_qty` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ยอดพยากรณ์อัตโนมัติ (Auto Forecast Qty)',
    `qty_actual_target` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ยอดขายจริงเดือนเป้าหมาย (Actual Target Sales)',
    `diff_qty` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ผลต่างยอดพยากรณ์เทียบ Avg 3M',
    `diff_percent` DECIMAL(10,2) DEFAULT 0.00 COMMENT '% ผลต่างเทียบ Avg 3M',
    `diff_actual_vs_forecast` DECIMAL(12,2) DEFAULT 0.00 COMMENT 'ผลต่าง ยอดขายจริง - ยอดพยากรณ์',
    `accuracy_percent` DECIMAL(10,2) DEFAULT 0.00 COMMENT '% ความแม่นยำ/บรรลุเป้า',
    `est_value` DECIMAL(14,2) DEFAULT 0.00 COMMENT 'ประเมินมูลค่ารวม (บาท)',
    `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT 'วันที่บันทึก',
    `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'วันที่อัปเดตล่าสุด',
    UNIQUE KEY `uk_target_group_ar_sku` (`target_year`, `target_month`, `group_by`, `ar_code`, `sku_code`),
    INDEX `idx_target_ym` (`target_year`, `target_month`),
    INDEX `idx_ar_code` (`ar_code`),
    INDEX `idx_sku_code` (`sku_code`),
    INDEX `idx_brand` (`brand`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='ตารางบันทึกข้อมูลพยากรณ์ยอดขายอัตโนมัติ (Auto Sales Forecast)';
