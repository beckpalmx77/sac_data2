-- SQL Command to create ims_tires_plan_forecast_realtime table
-- This table is used for the realtime Excel import feature

CREATE TABLE IF NOT EXISTS ims_tires_plan_forecast_realtime (
    id INT AUTO_INCREMENT PRIMARY KEY,
    forcast_month VARCHAR(50) NULL COMMENT 'เดือนที่คาดการณ์',
    forcast_year VARCHAR(4) NULL COMMENT 'ปีที่คาดการณ์',
    ar_code VARCHAR(50) NULL COMMENT 'รหัสร้านค้า',
    ar_name VARCHAR(255) NULL COMMENT 'ชื่อร้านค้า',
    sale_name VARCHAR(255) NULL COMMENT 'พนักงานขาย',
    take_name VARCHAR(255) NULL COMMENT 'คนเทค',
    team_name VARCHAR(100) NULL COMMENT 'ชื่อทีม',
    brand_code VARCHAR(100) NULL COMMENT 'ยี่ห้อสินค้า',
    sku_code VARCHAR(100) NULL COMMENT 'รหัสสินค้า',
    amphur VARCHAR(100) NULL COMMENT 'อำเภอ',
    province VARCHAR(100) NULL COMMENT 'จังหวัด',
    zone VARCHAR(100) NULL COMMENT 'เขตพื้นที่',
    avg_per_month_year DECIMAL(10,2) DEFAULT 0.00 COMMENT 'เฉลี่ยต่อเดือน ปีที่แล้ว',
    max_qty_year DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ยอดขายสูงสุดต่อเดือน',
    min_qty_year DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ยอดขายต่ำสุดต่อเดือน',
    target_qty_month DECIMAL(10,2) DEFAULT 0.00 COMMENT 'เป้ารายเดือน 1',
    sales_month_1 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ยอดขายเดือน M-1',
    sales_month_2 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ยอดขายเดือน M-2',
    sales_month_3 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ยอดขายเดือน M-3',
    avg_3_month DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ค่าเฉลี่ย 3 เดือน',
    target_qty_month_2 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'เป้ารายเดือน 2',
    forecast_qty_month_1 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'คาดการณ์ยอดขาย 1',
    compare_forecast_month_1 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ผลต่างเทียบคาดการณ์ 1',
    compare_sales_percent DECIMAL(10,2) DEFAULT 0.00 COMMENT 'เปอร์เซ็นต์ผลต่าง 1',
    remark TEXT NULL COMMENT 'หมายเหตุ',
    responsible_person VARCHAR(255) NULL COMMENT 'ผู้รับผิดชอบ',
    forecast_qty_month_2 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'คาดการณ์ยอดขาย 2',
    compare_forecast_month_2 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'ผลต่างเทียบคาดการณ์ 2',
    compare_sales_percent_2 DECIMAL(10,2) DEFAULT 0.00 COMMENT 'เปอร์เซ็นต์ผลต่าง 2',
    import_date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'วันที่นำเข้า',
    load_time INT DEFAULT 0 COMMENT 'จำนวนครั้งที่โหลดข้อมูล',
    INDEX idx_month_year (forcast_month, forcast_year),
    INDEX idx_cust_sku_sale (ar_code, sku_code, sale_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
